def _conditioned_constructor_kwargs(spec: CandidateSpec, k: int, seed: int) -> Dict[str, Any]:
    """Build one canonical wrapper call with no shared mutable nested state."""

    _strict_bool(spec.prototype_refinement)
    if spec.direct_control:
        raise ValueError("direct controls must use the upstream constructor")
    return {
        "estimator": str(spec.estimator),
        "weighting": spec.weighting,
        "gamma": float(spec.gamma),
        "prototype_refinement": spec.prototype_refinement,
        "conditioning_kwargs": {
            "condition_number_cap": 10000.0,
            "relative_eigenvalue_floor": 1e-8,
        },
        "overlap_index_kwargs": copy.deepcopy(oi_kwargs(k, seed)),
    }


def estimator_for(spec: CandidateSpec, k: int, seed: int) -> Any:
    """Construct a fresh candidate estimator for one paired case."""

    if not isinstance(spec, CandidateSpec):
        raise TypeError("spec must be a CandidateSpec")
    _strict_bool(spec.prototype_refinement)
    kwargs = oi_kwargs(k, seed)
    if spec.direct_control:
        from overlapindex import OverlapIndex

        # A/B are exact controls: no wrapper, no adapter aliases, and no
        # mutable mapping shared with another candidate.
        return OverlapIndex(
            **copy.deepcopy(kwargs),
            prototype_refinement=spec.prototype_refinement,
        )
    if spec.estimator not in {
        "oas_diagonal",
        "winsorized_oas_diagonal",
        "pooled_mad",
    }:
        raise ValueError("unknown conditioned estimator {!r}".format(spec.estimator))
    adapter = _conditioning_adapter()
    call_kwargs = _conditioned_constructor_kwargs(spec, k, seed)
    parameters = inspect.signature(adapter).parameters
    # The frozen follow-up adapter uses estimator/weighting/gamma.  The branch
    # below keeps an explicit failure for a stale mode-only adapter rather than
    # silently changing candidate semantics; it is useful to test seams before
    # the adapter implementation is integrated.
    if "estimator" not in parameters:
        raise TypeError(
            "conditioning adapter signature must expose estimator, weighting, and gamma"
        )
    return adapter(**call_kwargs)


