def _pair_indices(case: Any, n_rows: int, limit: int = 4096) -> List[Tuple[int, int]]:
    total = n_rows * (n_rows - 1) // 2
    if total <= limit:
        return [(first, second) for first in range(n_rows) for second in range(first + 1, n_rows)]
    seed_bytes = hashlib.sha256(canonical_json(_pair_identity_key(case)).encode("utf-8")).digest()
    random_seed = int.from_bytes(seed_bytes[:8], "big") % (2**63 - 1)
    rng = np.random.default_rng(random_seed)
    chosen = rng.choice(total, size=limit, replace=False)
    # Enumerating triangular indices is deterministic and avoids exposing a
    # hidden pair sampler in diagnostics.py.
    pairs: List[Tuple[int, int]] = []
    for flat in sorted(int(value) for value in chosen.tolist()):
        remaining = flat
        for first in range(n_rows - 1):
            width = n_rows - first - 1
            if remaining < width:
                pairs.append((first, first + 1 + remaining))
                break
            remaining -= width
    return pairs


class _IdentityScaleConditioner:
    """Tiny diagnostic-only identity conditioner for A/B fold stability."""

    def __init__(self, n_features: Optional[int] = None) -> None:
        self.n_features = n_features
        self.transform_ = None

    def fit(self, X: Any, labels: Any) -> "_IdentityScaleConditioner":
        values = np.asarray(X)
        self.transform_ = np.eye(values.shape[1], dtype=np.float64)
        return self


class _ConditionerOnly:
    """Fold-stability seam that fits conditioning state but never an OI model."""

    def __init__(self, estimator: str, weighting: Optional[str], gamma: float) -> None:
        self.estimator = str(estimator)
        self.weighting = weighting
        self.gamma = float(gamma)
        self.transform_ = None

    def fit(self, X: Any, labels: Any) -> "_ConditionerOnly":
        from . import conditioning_adapter

        values = np.asarray(X, dtype=np.float64)
        fitted = conditioning_adapter._fit_conditioner(
            values,
            np.asarray(labels).copy(),
            estimator=self.estimator,
            weighting=self.weighting,
            gamma=self.gamma,
        )
        self.transform_ = np.array(fitted.transform_, dtype=np.float64, copy=True)
        self.transform_.setflags(write=False)
        return self


def _fold_factory(spec: CandidateSpec, k: int, seed: int) -> Callable[[], Any]:
    if spec.direct_control:
        return _IdentityScaleConditioner
    # Fold stability is a conditioning diagnostic, not a second OI battery.
    # Construct the private conditioner-only seam so each fold fits no
    # prototypes and cannot accidentally contaminate runtime/outcome counts.
    return lambda: _ConditionerOnly(str(spec.estimator), spec.weighting, spec.gamma)


def _separated_mask(dataset: Any) -> np.ndarray:
    labels = np.asarray(dataset.evaluation.y)
    mask = np.ones(labels.shape[0], dtype=bool)
    if str(getattr(dataset.case, "signal_state", "")) == "genuine_overlap_half":
        components = np.asarray(dataset.evaluation.component_ids)
        mask &= ~(
            np.isin(labels, np.asarray([0, 1]))
            & (components == 0)
        )
    return mask


def _ordered_unique_labels(labels: Any) -> np.ndarray:
    """Return first-observed labels without NumPy mixed-type sorting."""

    values = np.asarray(labels, dtype=object).reshape(-1)
    unique: List[Any] = []
    for value in values.tolist():
        if value not in unique:
            unique.append(value)
    return np.asarray(unique, dtype=object)


