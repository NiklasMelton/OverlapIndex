def _json_safe(value: Any) -> Any:
    """Convert nested experiment values to finite JSON-compatible values."""

    if isinstance(value, np.ndarray):
        return [_json_safe(item) for item in value.tolist()]
    if isinstance(value, np.generic):
        return _json_safe(value.item())
    if isinstance(value, Mapping):
        return {str(key): _json_safe(item) for key, item in value.items()}
    if isinstance(value, (tuple, list)):
        return [_json_safe(item) for item in value]
    if isinstance(value, Path):
        return str(value)
    if isinstance(value, float):
        return float(value) if math.isfinite(value) else None
    if isinstance(value, (str, int, bool)) or value is None:
        return value
    if hasattr(value, "__dataclass_fields__"):
        return _json_safe(asdict(value))
    return repr(value)


def canonical_json(value: Any) -> str:
    return json.dumps(
        _json_safe(value),
        sort_keys=True,
        separators=(",", ":"),
        ensure_ascii=True,
        allow_nan=False,
    )


def sha256_bytes(value: bytes) -> str:
    return hashlib.sha256(value).hexdigest()


def digest(value: Any) -> str:
    return sha256_bytes(canonical_json(value).encode("utf-8"))


def validate_stage(stage: str) -> str:
    value = str(stage).strip().lower()
    if value not in STAGES:
        raise ValueError("stage must be one of {!r}; got {!r}.".format(STAGES, stage))
    return value


def _strict_bool(value: Any, name: str = "prototype_refinement") -> None:
    if type(value) is not bool:
        raise TypeError("{} must be a strict Python bool.".format(name))


def oi_kwargs(k: int, seed: int) -> Dict[str, Any]:
    """Return a fresh, deeply independent upstream OI kwargs mapping."""

    if isinstance(k, bool) or not isinstance(k, (int, np.integer)) or int(k) <= 0:
        raise ValueError("k must be a positive integer")
    kmeans_kwargs = copy.deepcopy(ARCHIVED_KMEANS_KWARGS)
    kmeans_kwargs["random_state"] = int(seed)
    return {
        "model_type": BACKEND,
        "kmeans_k": int(k),
        "kmeans_kwargs": kmeans_kwargs,
    }


