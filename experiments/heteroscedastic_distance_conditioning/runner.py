def _first_observed_integer_encoding(labels: Any) -> np.ndarray:
    values = np.asarray(labels, dtype=object).reshape(-1)
    classes: List[Any] = []
    encoded = np.empty(values.shape[0], dtype=np.int64)
    for index, label in enumerate(values.tolist()):
        found = None
        for position, previous in enumerate(classes):
            try:
                equal = bool(label == previous)
            except (TypeError, ValueError):
                equal = False
            if equal:
                found = position
                break
        if found is None:
            classes.append(label)
            found = len(classes) - 1
        encoded[index] = int(found)
    return encoded


def _reference_models(dataset: Any, seed: int) -> Tuple[Dict[str, float], Dict[str, float]]:
    """Fit the frozen held-out reference heads on one case's raw rows."""

    from sklearn.linear_model import LogisticRegression
    from sklearn.neighbors import KNeighborsClassifier
    from sklearn.pipeline import make_pipeline
    from sklearn.preprocessing import PolynomialFeatures
    from sklearn.svm import SVC

    X_train = np.asarray(dataset.train.X)
    X_eval = np.asarray(dataset.evaluation.X)
    y_train = _first_observed_integer_encoding(dataset.train.y)
    # The evaluation labels must use the same semantic classes as training.
    # Fixture labels are scalar integers, but this mapping keeps heterogeneous
    # object labels safe in outcome-free test seams.
    train_labels = np.asarray(dataset.train.y, dtype=object)
    eval_labels = np.asarray(dataset.evaluation.y, dtype=object)
    ordered: List[Any] = []
    for label in train_labels.tolist():
        if label not in ordered:
            ordered.append(label)
    eval_encoded_values: List[int] = []
    for label in eval_labels.tolist():
        try:
            eval_encoded_values.append(ordered.index(label))
        except ValueError as exc:
            raise ValueError("evaluation labels do not match training classes") from exc
    eval_encoded = np.asarray(eval_encoded_values, dtype=np.int64)
    models = (
        (
            "linear",
            LogisticRegression(max_iter=500, solver="lbfgs", random_state=int(seed)),
        ),
        (
            "quadratic",
            make_pipeline(
                PolynomialFeatures(degree=2, include_bias=False),
                LogisticRegression(max_iter=500, solver="lbfgs", random_state=int(seed)),
            ),
        ),
        ("knn", KNeighborsClassifier(n_neighbors=5)),
        ("rbf", SVC(kernel="rbf", C=1.0, gamma="scale")),
    )
    accuracies: Dict[str, float] = {}
    timings: Dict[str, float] = {}
    for name, estimator in models:
        started_wall = time.perf_counter()
        started_cpu = time.process_time()
        estimator.fit(X_train, y_train)
        predictions = np.asarray(estimator.predict(X_eval))
        accuracies[name] = float(np.mean(predictions == eval_encoded))
        timings[name] = float(max(0.0, time.perf_counter() - started_wall))
        timings[name + "_cpu_seconds"] = float(max(0.0, time.process_time() - started_cpu))
    return accuracies, timings


def _linear_probe_oof(X: Any, labels: Any, seed: int) -> Dict[str, Any]:
    """Return the exact five-fold training OOF selector score."""

    from sklearn.linear_model import LogisticRegression
    from sklearn.model_selection import StratifiedKFold
    from sklearn.preprocessing import StandardScaler

    values = np.asarray(X)
    encoded = _first_observed_integer_encoding(labels)
    splitter = StratifiedKFold(n_splits=5, shuffle=True, random_state=int(seed))
    predictions = np.empty(encoded.shape[0], dtype=np.int64)
    fold_rows: List[Dict[str, int]] = []
    for train_rows, holdout_rows in splitter.split(np.zeros(values.shape[0]), encoded):
        scaler = StandardScaler()
        train_values = scaler.fit_transform(values[train_rows])
        holdout_values = scaler.transform(values[holdout_rows])
        estimator = LogisticRegression(
            C=1.0,
            solver="lbfgs",
            max_iter=2000,
            n_jobs=1,
            random_state=int(seed),
        )
        estimator.fit(train_values, encoded[train_rows])
        predictions[holdout_rows] = np.asarray(estimator.predict(holdout_values), dtype=np.int64)
        fold_rows.append({"train": int(train_rows.size), "heldout": int(holdout_rows.size)})
    return {
        "score": float(np.mean(predictions == encoded)),
        "predictions": predictions.tolist(),
        "folds": fold_rows,
        "fold_count": len(fold_rows),
    }


def linear_probe_oof(X: Any, labels: Any, seed: int) -> float:
    return float(_linear_probe_oof(X, labels, seed)["score"])


def _clock() -> Tuple[float, float]:
    return time.perf_counter(), time.process_time()


def _elapsed(start: Tuple[float, float]) -> Tuple[float, float]:
    wall, cpu = _clock()
    return max(0.0, wall - start[0]), max(0.0, cpu - start[1])


