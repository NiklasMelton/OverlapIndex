def _provenance() -> Dict[str, Any]:
    """Collect source identity while excluding generated output roots."""

    protocol_path = ROOT / "experiments/heteroscedastic_distance_conditioning/protocol.json"
    protocol_bytes = protocol_path.read_bytes()
    protocol_payload = json.loads(protocol_bytes.decode("utf-8"))
    repository_payload = dict(protocol_payload.get("repository", {}))
    expected_starting = str(repository_payload.get("starting_commit", ""))
    expected_develop_base = str(
        repository_payload.get("original_develop_base", expected_starting)
    )
    if not expected_starting or not expected_develop_base:
        raise RuntimeError("frozen protocol does not declare both starting commits")
    try:
        head = subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=str(ROOT), text=True).strip()
        branch = subprocess.check_output(["git", "branch", "--show-current"], cwd=str(ROOT), text=True).strip()
        develop = subprocess.check_output(["git", "rev-parse", "develop"], cwd=str(ROOT), text=True).strip()
        merge_base = subprocess.check_output(["git", "merge-base", "HEAD", "develop"], cwd=str(ROOT), text=True).strip()
        starting_merge_base = subprocess.check_output(["git", "merge-base", "HEAD", expected_starting], cwd=str(ROOT), text=True).strip()
    except (OSError, subprocess.CalledProcessError) as exc:
        raise RuntimeError("cannot collect git provenance") from exc
    if branch != str(repository_payload.get("branch", branch)):
        raise RuntimeError("experiment is running on an unexpected branch")
    if develop != expected_develop_base or merge_base != expected_develop_base:
        raise RuntimeError(
            "recorded develop base mismatch: expected {}, develop={}, merge_base={}"
            .format(expected_develop_base, develop, merge_base)
        )
    if starting_merge_base != expected_starting:
        raise RuntimeError(
            "experiment starting commit is not an ancestor of HEAD: expected {}"
            .format(expected_starting)
        )
    # A production stage may not record a partial identity.  The source list
    # is explicit in manifest.py and excludes generated output roots.
    source_hashes = manifest.source_hashes(ROOT, require_existing=True)
    status = ""
    try:
        status = subprocess.check_output(
            ["git", "status", "--porcelain=v1", "--untracked-files=all"],
            cwd=str(ROOT),
            text=True,
        ).strip()
    except (OSError, subprocess.CalledProcessError):
        pass
    protocol_sha256 = sha256_bytes(protocol_bytes)
    # Use the manifest's canonical identity implementation so decision files,
    # resume checks, and raw artifacts cannot disagree about the source scope.
    code_identity = manifest.code_identity_sha256(ROOT, source_hashes, require_existing=True)
    return {
        "branch": branch,
        "starting_commit": expected_starting,
        "original_develop_base": expected_develop_base,
        "develop_commit_at_execution": develop,
        "merge_base_with_develop": merge_base,
        "experiment_start_commit_verified": starting_merge_base,
        "experiment_commit": head,
        "source_hashes": _json_safe(source_hashes),
        "protocol_sha256": protocol_sha256,
        "code_identity_sha256": code_identity,
        "working_tree_hash": code_identity,
        "source_hashes_required": True,
        "git_dirty": bool(status),
        "git_status_sha256": sha256_bytes(status.encode("utf-8")),
        "output_root_excluded_from_code_identity": True,
    }


def _authorize_stage(
    stage: str,
    *,
    provenance: Mapping[str, Any],
    implementation_review: Any = None,
    smoke_decision: Any = None,
    pre_screen_review: Any = None,
    promotion_decision: Any = None,
    prior_regression_decision: Any = None,
) -> Any:
    code_hash = provenance.get("code_identity_sha256")
    protocol_hash = manifest.verify_protocol_hash()
    if stage == "smoke":
        if implementation_review is None:
            raise PermissionError("smoke requires a hashed implementation_review.json with status go")
        manifest.validate_implementation_review(
            implementation_review,
            protocol_hash=protocol_hash,
            code_identity_hash=code_hash,
        )
        return None
    if stage == "development":
        if smoke_decision is None or pre_screen_review is None:
            raise PermissionError("development requires structural smoke and pre-screen review decisions")
        manifest.validate_smoke_decision(smoke_decision, protocol_hash=protocol_hash, code_identity_hash=code_hash)
        manifest.validate_pre_screen_review(pre_screen_review, protocol_hash=protocol_hash, code_identity_hash=code_hash)
        smoke_payload = _decision_payload(smoke_decision)
        pre_screen_payload = _decision_payload(pre_screen_review)
        smoke_manifest_hash = smoke_payload.get("input_manifest_sha256")
        if not isinstance(smoke_manifest_hash, str) or not smoke_manifest_hash:
            raise PermissionError(
                "smoke decision must identify its input manifest with input_manifest_sha256"
            )
        expected_smoke_hash = _decision_hash(smoke_decision)
        observed_smoke_hash = pre_screen_payload.get(
            "smoke_decision_sha256",
            pre_screen_payload.get("smoke_decision_hash"),
        )
        if observed_smoke_hash != expected_smoke_hash:
            raise PermissionError(
                "pre-screen review does not reference the supplied smoke decision bytes"
            )
        pre_screen_manifest_hash = pre_screen_payload.get(
            "smoke_manifest_sha256",
            pre_screen_payload.get("input_manifest_sha256"),
        )
        if pre_screen_manifest_hash != smoke_manifest_hash:
            raise PermissionError(
                "pre-screen review and smoke decision reference different manifests"
            )
        return None
    if stage == "confirmation":
        if promotion_decision is None or prior_regression_decision is None:
            raise PermissionError("confirmation requires promotion and prior-regression decisions")
        token = manifest.authorize_confirmation(
            promotion_decision,
            prior_regression_decision,
            protocol_hash=protocol_hash,
            code_identity_hash=code_hash,
        )
        manifest.validate_confirmation_authorization(token, protocol_hash=protocol_hash)
        return token
    raise ValueError("unknown stage")


def authorize_stage(stage: str, **kwargs: Any) -> Any:
    return _authorize_stage(validate_stage(stage), **kwargs)


def _validate_stage_cases(stage: str, cases: Sequence[Any], supplied: bool) -> None:
    """Reject truncated/reordered frozen grids outside the smoke seam."""

    expected = stage_cases(stage)
    observed_ids = [case_id(case) for case in cases]
    expected_ids = [case_id(case) for case in expected]
    if observed_ids != expected_ids:
        raise ValueError("{} case grid does not exactly match the frozen manifest".format(stage))
    # The manifest validator also checks exact count, seed set, and rank
    # marginals.  Keep this check in the runner so a caller cannot bypass it by
    # supplying objects with a matching-looking case_id.
    manifest.validate_case_grid(tuple(cases), stage=stage)


def _atomic_write_bytes(path: Path, payload: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temporary = tempfile.mkstemp(prefix=".partial-", dir=str(path.parent))
    try:
        with os.fdopen(fd, "wb") as handle:
            handle.write(payload)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(temporary, path)
    except Exception:
        try:
            os.unlink(temporary)
        except OSError:
            pass
        raise


def _checkpoint_path(output_dir: Path, case_identifier: str) -> Path:
    if not case_identifier or any(char in case_identifier for char in ("/", "\\", "..")):
        raise ValueError("case id is not a safe checkpoint identity")
    return output_dir / "checkpoints" / (case_identifier + ".json")


def _checkpoint_expected_methods(identity: Mapping[str, Any]) -> Tuple[str, ...]:
    """Return and validate the frozen method block for a checkpoint.

    Checkpoint reuse is deliberately stricter than table assembly.  A partial
    or hand-edited row block must not be mistaken for a completed paired case,
    even when its outer identity happens to match.  The confirmation lock is
    represented by the optional final method in its canonical method block;
    the checkpoint identity already includes the complete ordered method list.
    """

    stage = str(identity.get("stage", "")).strip().lower()
    methods_value = identity.get("methods")
    if isinstance(methods_value, (str, bytes)) or not isinstance(methods_value, (list, tuple)):
        raise RuntimeError("checkpoint identity must contain an ordered methods list")
    methods = tuple(str(value) for value in methods_value)
    if not methods or len(methods) != len(set(methods)):
        raise RuntimeError("checkpoint identity methods must be unique and non-empty")
    unknown = [method for method in methods if method not in CANDIDATE_BY_ID]
    if unknown:
        raise RuntimeError("checkpoint identity contains unknown methods {!r}".format(unknown))

    if stage in {"smoke", "development"}:
        expected = tuple(str(value) for value in manifest.methods_for_stage(stage))
    elif stage == "confirmation":
        base = tuple(str(value) for value in manifest.methods_for_stage(stage))
        if methods[: len(base)] != base or len(methods) not in {len(base), len(base) + 1}:
            raise RuntimeError("checkpoint identity does not use the canonical confirmation methods")
        if len(methods) == len(base):
            expected = base
        else:
            # methods_for_stage validates that the extra method is promotable
            # and appends it only when it is not already in the fixed base.
            expected = tuple(str(value) for value in manifest.methods_for_stage(stage, methods[-1]))
    else:
        raise RuntimeError("checkpoint identity has unsupported stage {!r}".format(stage))
    if methods != expected:
        raise RuntimeError(
            "checkpoint identity methods do not match canonical {} order: expected {!r}, got {!r}".format(
                stage, expected, methods
            )
        )
    return expected


def _validate_reusable_checkpoint_payload(
    payload: Mapping[str, Any],
    identity: Mapping[str, Any],
    case_identifier: str,
) -> None:
    """Reject anything other than a complete, successful case checkpoint."""

    expected_methods = _checkpoint_expected_methods(identity)
    if payload.get("case_id") != case_identifier:
        raise RuntimeError("checkpoint payload case_id mismatch for {}".format(case_identifier))
    if "outcomes_redacted" not in payload or type(payload.get("outcomes_redacted")) is not bool:
        raise RuntimeError("checkpoint payload outcomes_redacted must be a boolean for {}".format(case_identifier))
    expected_redacted = str(identity.get("stage", "")).strip().lower() == "smoke"
    if payload["outcomes_redacted"] is not expected_redacted:
        raise RuntimeError(
            "checkpoint payload outcomes_redacted disagrees with stage for {}".format(case_identifier)
        )

    for marker in ("error", "stop_reason", "stopped"):
        value = payload.get(marker)
        if value not in (None, "", False, []):
            raise RuntimeError("checkpoint payload contains {} marker for {}".format(marker, case_identifier))
    if "status" in payload and payload.get("status") not in (None, "", "ok", "completed"):
        raise RuntimeError("checkpoint payload status is not reusable for {}".format(case_identifier))

    rows = payload.get("rows")
    if not isinstance(rows, list):
        raise RuntimeError("checkpoint payload rows must be a list for {}".format(case_identifier))
    if any(not isinstance(row, Mapping) for row in rows):
        raise RuntimeError("checkpoint payload rows must be objects for {}".format(case_identifier))
    observed_methods = [row.get("candidate_id") for row in rows]
    if observed_methods != list(expected_methods):
        raise RuntimeError(
            "checkpoint payload rows do not exactly match canonical method order for {}".format(case_identifier)
        )
    for method, row in zip(expected_methods, rows):
        if row.get("status") != "ok":
            raise RuntimeError(
                "checkpoint candidate {} is not reusable (status={!r}) for {}".format(
                    method, row.get("status"), case_identifier
                )
            )
        for marker in ("error", "stop_reason", "stopped"):
            value = row.get(marker)
            if value not in (None, "", False, []):
                raise RuntimeError(
                    "checkpoint candidate {} contains {} marker for {}".format(method, marker, case_identifier)
                )
        if row.get("outcomes_redacted", False) is not expected_redacted:
            raise RuntimeError(
                "checkpoint candidate {} outcomes_redacted disagrees with stage for {}".format(
                    method, case_identifier
                )
            )


def _write_checkpoint(output_dir: Path, payload: Mapping[str, Any], identity: Mapping[str, Any]) -> None:
    safe_payload = _json_safe(payload)
    if not isinstance(safe_payload, Mapping):
        raise TypeError("checkpoint payload must be a mapping")
    record = {
        "schema_version": SCHEMA_VERSION,
        "identity_sha256": digest(identity),
        "identity": _json_safe(identity),
        # Hash the canonical serialized payload itself.  This is separate from
        # identity_sha256 so an unchanged case identity cannot hide tampered or
        # incomplete row content on resume.
        "payload_sha256": digest(safe_payload),
        "payload": safe_payload,
    }
    _atomic_write_bytes(
        _checkpoint_path(output_dir, str(identity["case_id"])),
        (canonical_json(record) + "\n").encode("utf-8"),
    )


def _read_checkpoint(output_dir: Path, case_identifier: str, identity: Mapping[str, Any]) -> Optional[Dict[str, Any]]:
    path = _checkpoint_path(output_dir, case_identifier)
    if not path.is_file():
        return None
    try:
        record = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise RuntimeError("invalid checkpoint {}".format(path)) from exc
    if not isinstance(record, Mapping):
        raise RuntimeError("checkpoint record is not an object for {}".format(case_identifier))
    if record.get("schema_version") != SCHEMA_VERSION:
        raise RuntimeError("checkpoint schema mismatch for {}".format(case_identifier))
    expected_identity = _json_safe(identity)
    if (
        record.get("identity_sha256") != digest(identity)
        or canonical_json(record.get("identity")) != canonical_json(expected_identity)
    ):
        raise RuntimeError("checkpoint identity mismatch for {}".format(case_identifier))
    payload = record.get("payload")
    if not isinstance(payload, Mapping):
        raise RuntimeError("checkpoint payload is not an object for {}".format(case_identifier))
    payload_hash = record.get("payload_sha256")
    if not isinstance(payload_hash, str) or payload_hash != digest(payload):
        raise RuntimeError("checkpoint payload hash mismatch for {}".format(case_identifier))
    _validate_reusable_checkpoint_payload(payload, identity, case_identifier)
    return dict(payload)


def _flatten_rows(checkpoints: Sequence[Mapping[str, Any]]) -> List[Dict[str, Any]]:
    rows: List[Dict[str, Any]] = []
    for checkpoint in checkpoints:
        rows.extend(dict(row) for row in checkpoint.get("rows", ()))
    return rows


def _truth_for_pair(truth: Mapping[str, Any], source: Any, target: Any) -> Dict[str, Any]:
    """Attach frozen pair truth to normalized evidence rows."""

    overlap = truth.get("truth_pair_overlap", truth.get("pair_overlap"))
    labels = truth.get("truth_overlap_label", truth.get("pair_overlap_label"))
    result: Dict[str, Any] = {
        "truth_overlap": None,
        "truth_overlap_label": None,
        "designated_pair": False,
        "overlap_severity": truth.get("overlap_severity"),
    }
    try:
        source_index = int(source)
        target_index = int(target)
        overlap_array = np.asarray(overlap)
        label_array = np.asarray(labels)
        if (
            overlap_array.ndim != 2
            or label_array.ndim != 2
            or overlap_array.shape != label_array.shape
            or source_index < 0
            or target_index < 0
            or source_index >= overlap_array.shape[0]
            or target_index >= overlap_array.shape[1]
        ):
            raise ValueError("truth pair matrix has incompatible dimensions")
        result["truth_overlap"] = float(overlap_array[source_index, target_index])
        result["truth_overlap_label"] = int(label_array[source_index, target_index])
        designated = truth.get("overlap_pairs", ())
        result["designated_pair"] = any(
            list(pair) == [source_index, target_index]
            or list(pair) == [target_index, source_index]
            for pair in designated
        )
    except (TypeError, ValueError, IndexError, OverflowError):
        # Non-integer semantic labels are valid for diagnostics, but their
        # class-index truth is unavailable in this matrix representation.
        pass
    return _json_safe(result)


def _table_rows(
    checkpoints: Sequence[Mapping[str, Any]],
    resource_rows: Sequence[Mapping[str, Any]] = (),
) -> Dict[str, List[Dict[str, Any]]]:
    case_rows: List[Dict[str, Any]] = []
    geometry_rows: List[Dict[str, Any]] = []
    prototype_rows: List[Dict[str, Any]] = []
    pair_rows: List[Dict[str, Any]] = []
    selector_rows: List[Dict[str, Any]] = []
    for checkpoint in checkpoints:
        case_identity = dict(checkpoint.get("case", {}))
        for row in checkpoint.get("rows", ()):
            base = {
                **case_identity,
                "case_id": checkpoint.get("case_id"),
                "candidate_id": row.get("candidate_id"),
                "status": row.get("status"),
            }
            case_rows.append({**case_identity, **{key: value for key, value in row.items() if key not in {"geometry", "prototype", "pairwise", "truth"}}})
            if row.get("geometry") is not None:
                geometry_rows.append({**base, "geometry": row.get("geometry")})
            if row.get("prototype") is not None:
                prototype_rows.append({**base, "prototype": row.get("prototype"), "refinement": row.get("refinement_stage")})
            if row.get("outcomes_redacted"):
                # Structural smoke rows retain directional identities only.
                # Never reconstruct evidence/truth values from a redacted row.
                for pair_identity in row.get("smoke_pair_identities", ()):
                    if not isinstance(pair_identity, Mapping):
                        continue
                    pair_structure = pair_identity.get("pair_structure")
                    expected_pair_fields = {
                        "support",
                        "hits",
                        "sparse_adj_hits",
                        "pairwise_index",
                        "evidence",
                    }
                    if not isinstance(pair_structure, Mapping) or set(pair_structure) != expected_pair_fields:
                        raise RuntimeError("smoke pair identity lacks canonical pair_structure descriptors")
                    for descriptor in pair_structure.values():
                        if not isinstance(descriptor, Mapping) or set(descriptor) != {
                            "present",
                            "type",
                            "finite",
                        }:
                            raise RuntimeError("smoke pair_structure descriptor has an invalid schema")
                    pair_rows.append(
                        {
                            **base,
                            "source_label": pair_identity.get("source_label"),
                            "target_label": pair_identity.get("target_label"),
                            "exact_state_match": bool(
                                (row.get("state_identity") or {}).get("exact_state_match", False)
                            ),
                            "pair_structure": pair_structure,
                            "outcomes_redacted": True,
                        }
                    )
                # Candidate evidence is intentionally absent from smoke.
                continue
            pairwise = row.get("pairwise", {}) or {}
            for pair in pairwise.get("directional_pair_support_hits_evidence", ()):
                pair_value = dict(pair)
                pair_rows.append(
                    {
                        **base,
                        **pair_value,
                        **_truth_for_pair(
                            row.get("truth", {}) or {},
                            pair_value.get("source_label"),
                            pair_value.get("target_label"),
                        ),
                    }
                )
            probe = row.get("linear_probe")
            selector_rows.append(
                {
                    **base,
                    "candidate_name": row.get("candidate_name"),
                    "candidate_score": row.get("candidate_score"),
                    "reference_accuracies": row.get("reference_accuracies"),
                    "linear_probe_score": (
                        probe.get("score")
                        if isinstance(probe, Mapping)
                        else row.get("linear_probe_score")
                    ),
                    "outcomes_redacted": row.get("outcomes_redacted", False),
                }
            )
    # Normalized tables are consumed as paired arrays by the statistics layer.
    # Their byte order is therefore part of the frozen artifact contract: case
    # order follows the frozen case grid and candidate order follows the
    # stage's method list (not lexical candidate-id order).  Pair evidence has
    # an additional canonical source/target direction key.  Do not use the
    # serialized row as the primary key; that would put ``P25`` before ``B``
    # and make table order depend on incidental nested diagnostic fields.
    observed_case_ids: List[str] = []
    observed_candidate_ids: List[str] = []
    for checkpoint in checkpoints:
        observed_case = str(checkpoint.get("case_id", ""))
        if observed_case not in observed_case_ids:
            observed_case_ids.append(observed_case)
        for row in checkpoint.get("rows", ()):
            candidate = str(row.get("candidate_id", ""))
            if candidate not in observed_candidate_ids:
                observed_candidate_ids.append(candidate)
    for resource_row in resource_rows:
        if not isinstance(resource_row, Mapping):
            continue
        resource_case = resource_row.get("case", {})
        observed_case = str(
            resource_row.get(
                "case_id",
                resource_case.get("case_id", "") if isinstance(resource_case, Mapping) else "",
            )
        )
        if observed_case not in observed_case_ids:
            observed_case_ids.append(observed_case)
        candidate = str(resource_row.get("candidate_id", ""))
        if candidate not in observed_candidate_ids:
            observed_candidate_ids.append(candidate)

    def expected_case_ids() -> List[str]:
        # Use the protocol's case-grid order when this is a frozen stage.  A
        # small/fake checkpoint seam may use synthetic ids; those retain their
        # supplied order after all known frozen ids are considered.
        stage = ""
        for checkpoint in checkpoints:
            case = checkpoint.get("case", {})
            if isinstance(case, Mapping) and case.get("stage") is not None:
                stage = str(case.get("stage"))
                break
        if not stage:
            for resource_row in resource_rows:
                if isinstance(resource_row, Mapping) and resource_row.get("stage") is not None:
                    stage = str(resource_row.get("stage"))
                    break
        try:
            frozen_cases = stage_cases(stage) if stage in STAGES else ()
        except Exception:
            frozen_cases = ()
        frozen_ids = [case_id(case) for case in frozen_cases]
        return [identifier for identifier in frozen_ids if identifier in observed_case_ids] + [
            identifier for identifier in observed_case_ids if identifier not in frozen_ids
        ]

    case_order = {identifier: position for position, identifier in enumerate(expected_case_ids())}

    def expected_candidate_ids() -> List[str]:
        observed = set(observed_candidate_ids)
        # Confirmation has a stage-specific base order followed by exactly
        # one locked candidate.  Infer that shape from the observed set so the
        # table helper remains independent of authorization artifacts.
        confirmation_base = tuple(manifest.methods_for_stage("confirmation", None))
        if set(confirmation_base).issubset(observed) and len(observed) <= len(confirmation_base) + 1:
            extras = [candidate for candidate in observed_candidate_ids if candidate not in confirmation_base]
            locked_candidate = extras[0] if extras else None
            return list(manifest.methods_for_stage("confirmation", locked_candidate))
        return [candidate for candidate in METHOD_IDS if candidate in observed] + [
            candidate for candidate in observed_candidate_ids if candidate not in METHOD_IDS
        ]

    candidate_order = {
        identifier: position for position, identifier in enumerate(expected_candidate_ids())
    }

    def ordered(rows: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
        def direction_value(value: Any) -> Tuple[Any, ...]:
            value = _json_safe(value)
            if value is None:
                return (0, "")
            if isinstance(value, bool):
                return (1, int(value))
            if isinstance(value, int):
                return (2, value)
            if isinstance(value, float) and math.isfinite(value):
                return (3, value)
            if isinstance(value, str):
                return (4, value)
            return (5, canonical_json(value))

        def row_key(row: Mapping[str, Any]) -> Tuple[Any, ...]:
            case_identifier = str(row.get("case_id", ""))
            candidate_identifier = str(row.get("candidate_id", ""))
            direction = (
                0,
                direction_value(row.get("source_label")),
                direction_value(row.get("target_label")),
            ) if "source_label" in row or "target_label" in row else (1, "", "")
            return (
                case_order.get(case_identifier, len(case_order)),
                candidate_order.get(candidate_identifier, len(candidate_order)),
                direction,
                canonical_json(row),
            )

        return sorted(rows, key=row_key)

    def ordered_resources(rows: Sequence[Mapping[str, Any]]) -> List[Dict[str, Any]]:
        # Resource rows are measured in a counterbalanced worker order, but
        # normalized tables use the same canonical case/method order as every
        # other table.  Keep the execution position as data, never as the
        # serialization order key.
        resource_order = {"R0": 0, "R1": 1, "R2": 2, "R3": 3}

        def resource_key(row: Mapping[str, Any]) -> Tuple[Any, ...]:
            resource_case = row.get("case", {})
            case_identifier = str(
                row.get(
                    "case_id",
                    resource_case.get("case_id", "")
                    if isinstance(resource_case, Mapping)
                    else "",
                )
            )
            candidate_identifier = str(row.get("candidate_id", ""))
            return (
                resource_order.get(str(row.get("resource_id", "")), len(resource_order)),
                case_order.get(case_identifier, len(case_order)),
                candidate_order.get(candidate_identifier, len(candidate_order)),
                canonical_json(row),
            )

        return [dict(row) for row in sorted(rows, key=resource_key)]
    return {
        "case_rows.jsonl": ordered(case_rows),
        "geometry_rows.jsonl": ordered(geometry_rows),
        "prototype_rows.jsonl": ordered(prototype_rows),
        "pair_rows.jsonl": ordered(pair_rows),
        "selector_panels.jsonl": ordered(selector_rows),
        "resource_rows.jsonl": ordered_resources(resource_rows),
    }


def _write_jsonl(path: Path, rows: Sequence[Mapping[str, Any]]) -> str:
    payload = b"".join((canonical_json(row) + "\n").encode("utf-8") for row in rows)
    _atomic_write_bytes(path, payload)
    return sha256_bytes(payload)


def assemble_tables(
    output_dir: Union[str, Path],
    checkpoints: Sequence[Mapping[str, Any]],
    resource_rows: Sequence[Mapping[str, Any]] = (),
) -> Dict[str, Any]:
    output = Path(output_dir)
    tables_dir = output / "tables"
    table_rows = _table_rows(checkpoints, resource_rows)
    table_manifest: Dict[str, Any] = {}
    for name, rows in table_rows.items():
        path = tables_dir / name
        file_hash = _write_jsonl(path, rows)
        table_manifest[name] = {
            "schema_version": SCHEMA_VERSION,
            "path": "tables/{}".format(name),
            "row_count": len(rows),
            "sha256": file_hash,
        }
    return table_manifest


def _manifest_identity(payload: Mapping[str, Any]) -> Dict[str, Any]:
    """Project a stage manifest to fields that must not change on resume."""

    provenance = payload.get("provenance", {})
    if not isinstance(provenance, Mapping):
        provenance = {}
    environment = payload.get("environment")
    environment_sha256 = payload.get("environment_sha256")
    if environment_sha256 is None and environment is not None:
        environment_sha256 = digest(environment)
    return {
        "stage": payload.get("stage"),
        "protocol_sha256": payload.get("protocol_sha256", provenance.get("protocol_sha256")),
        "code_identity_sha256": payload.get(
            "code_identity_sha256", provenance.get("code_identity_sha256")
        ),
        "source_hashes": provenance.get("source_hashes", payload.get("source_hashes")),
        "method_ids": payload.get("method_ids"),
        "locked_candidate": payload.get("locked_candidate"),
        "case_grid_sha256": payload.get("case_grid_sha256"),
        "authorization_hashes": payload.get("authorization_hashes"),
        "environment_sha256": environment_sha256,
    }


def _expected_manifest_identity(
    stage_meta: Mapping[str, Any], provenance: Mapping[str, Any]
) -> Dict[str, Any]:
    """Build the immutable identity projection before any output is written."""

    return _manifest_identity(
        {
            **dict(stage_meta),
            "provenance": dict(provenance),
        }
    )


def _assert_manifest_identity(
    observed: Mapping[str, Any],
    expected: Mapping[str, Any],
    *,
    source: str,
) -> None:
    observed_identity = _manifest_identity(observed)
    for key, expected_value in expected.items():
        if canonical_json(observed_identity.get(key)) != canonical_json(expected_value):
            raise RuntimeError(
                "existing {} identity mismatch for {}: expected {!r}, got {!r}".format(
                    source, key, expected_value, observed_identity.get(key)
                )
            )


def _checkpoint_identity_projection(identity: Mapping[str, Any]) -> Dict[str, Any]:
    """Return common checkpoint identity fields available before bank hashing."""

    return {
        "stage": identity.get("stage"),
        "protocol_sha256": identity.get("protocol_sha256"),
        "code_identity_sha256": identity.get("code_identity_sha256"),
        "source_hashes": identity.get("source_hashes"),
        "methods": identity.get("methods"),
        "authorization_hashes": identity.get("authorization_hashes"),
        "environment_sha256": identity.get("environment_sha256"),
    }


def _preflight_existing_checkpoints(
    output_dir: Path,
    *,
    expected_identity: Mapping[str, Any],
    expected_case_ids: Sequence[str],
) -> None:
    """Reject stale/tampered checkpoints before the first manifest write."""

    checkpoint_dir = output_dir / "checkpoints"
    if not checkpoint_dir.exists():
        return
    if not checkpoint_dir.is_dir():
        raise RuntimeError("checkpoint path is not a directory: {}".format(checkpoint_dir))
    expected_cases = {str(value) for value in expected_case_ids}
    expected_checkpoint = {
        "stage": expected_identity.get("stage"),
        "protocol_sha256": expected_identity.get("protocol_sha256"),
        "code_identity_sha256": expected_identity.get("code_identity_sha256"),
        "source_hashes": expected_identity.get("source_hashes"),
        "methods": expected_identity.get("method_ids"),
        "authorization_hashes": expected_identity.get("authorization_hashes"),
        "environment_sha256": expected_identity.get("environment_sha256"),
    }
    for path in sorted(checkpoint_dir.glob("*.json")):
        try:
            record = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as exc:
            raise RuntimeError("invalid existing checkpoint {}".format(path)) from exc
        if not isinstance(record, Mapping):
            raise RuntimeError("existing checkpoint is not an object: {}".format(path))
        if record.get("schema_version") != SCHEMA_VERSION:
            raise RuntimeError("existing checkpoint schema mismatch: {}".format(path))
        identity = record.get("identity")
        if not isinstance(identity, Mapping):
            raise RuntimeError("existing checkpoint lacks identity: {}".format(path))
        if record.get("identity_sha256") != digest(identity):
            raise RuntimeError("existing checkpoint identity hash mismatch: {}".format(path))
        checkpoint_case_id = str(identity.get("case_id", ""))
        if checkpoint_case_id not in expected_cases:
            raise RuntimeError(
                "existing checkpoint case is outside the requested stage grid: {}".format(path)
            )
        if path.stem != checkpoint_case_id:
            raise RuntimeError("existing checkpoint filename/case mismatch: {}".format(path))
        observed_checkpoint = _checkpoint_identity_projection(identity)
        for key, expected_value in expected_checkpoint.items():
            if canonical_json(observed_checkpoint.get(key)) != canonical_json(expected_value):
                raise RuntimeError(
                    "existing checkpoint identity mismatch for {}: {}".format(key, path)
                )
        payload = record.get("payload")
        payload_hash = record.get("payload_sha256")
        if not isinstance(payload, Mapping) or not isinstance(payload_hash, str):
            raise RuntimeError("existing checkpoint lacks canonical payload hash: {}".format(path))
        if payload_hash != digest(payload):
            raise RuntimeError("existing checkpoint payload hash mismatch: {}".format(path))


def _preflight_existing_output(
    output_dir: Path,
    *,
    stage_meta: Mapping[str, Any],
    provenance: Mapping[str, Any],
    expected_case_ids: Sequence[str],
) -> str:
    """Validate an existing output before allowing any mutation.

    Returns ``"new"`` for an empty/non-finalized output, ``"resume"`` for a
    same-identity partial/stopped output, and ``"completed"`` for a complete
    artifact that must be treated as read-only.
    """

    expected_identity = _expected_manifest_identity(stage_meta, provenance)
    manifest_path = output_dir / "manifest.json"
    raw_path = output_dir / "raw_results.json"
    if output_dir.exists() and not output_dir.is_dir():
        raise RuntimeError("stage output exists but is not a directory: {}".format(output_dir))
    if not output_dir.exists():
        return "new"

    manifest_payload: Optional[Mapping[str, Any]] = None
    raw_payload: Optional[Mapping[str, Any]] = None
    if manifest_path.exists():
        try:
            value = json.loads(manifest_path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as exc:
            raise RuntimeError("invalid existing stage manifest {}".format(manifest_path)) from exc
        if not isinstance(value, Mapping):
            raise RuntimeError("existing stage manifest is not an object: {}".format(manifest_path))
        manifest_payload = value
        _assert_manifest_identity(value, expected_identity, source="manifest")
    if raw_path.exists():
        try:
            value = json.loads(raw_path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as exc:
            raise RuntimeError("invalid existing raw artifact {}".format(raw_path)) from exc
        if not isinstance(value, Mapping):
            raise RuntimeError("existing raw artifact is not an object: {}".format(raw_path))
        raw_payload = value
        # The nested manifest is authoritative for the normalized artifact,
        # but the raw envelope repeats the core identity.  Check both so a
        # hand-edited raw status/protocol cannot make an incompatible output
        # look reusable.
        raw_envelope_identity = _manifest_identity(
            {
                "stage": value.get("stage"),
                "protocol_sha256": value.get("manifest", {}).get("protocol_sha256")
                if isinstance(value.get("manifest"), Mapping)
                else value.get("protocol_sha256"),
                "provenance": value.get("provenance", {}),
                "environment": value.get("environment"),
            }
        )
        for key in ("stage", "protocol_sha256", "code_identity_sha256", "source_hashes", "environment_sha256"):
            if canonical_json(raw_envelope_identity.get(key)) != canonical_json(expected_identity.get(key)):
                raise RuntimeError(
                    "existing raw artifact identity mismatch for {}".format(key)
                )
        nested_manifest = value.get("manifest")
        if not isinstance(nested_manifest, Mapping):
            raise RuntimeError("existing raw artifact lacks nested manifest: {}".format(raw_path))
        _assert_manifest_identity(nested_manifest, expected_identity, source="raw manifest")
        if manifest_payload is not None:
            if canonical_json(manifest_payload) != canonical_json(nested_manifest):
                raise RuntimeError("existing manifest and raw nested manifest disagree")
        nested_tables = nested_manifest.get("table_manifest")
        envelope_tables = value.get("table_manifest")
        if envelope_tables is not None and canonical_json(envelope_tables) != canonical_json(nested_tables):
            raise RuntimeError("existing raw artifact and manifest table declarations disagree")
        envelope_summary_hash = value.get("summary_sha256")
        nested_summary_hash = nested_manifest.get("summary_sha256")
        if envelope_summary_hash is not None and envelope_summary_hash != nested_summary_hash:
            raise RuntimeError("existing raw artifact and manifest summary hashes disagree")
        for key in (
            "artifact_status",
            "expected_case_count",
            "observed_case_count",
            "expected_method_row_count",
            "observed_method_row_count",
            "resource_row_count",
        ):
            if key in value and key in nested_manifest:
                if canonical_json(value.get(key)) != canonical_json(nested_manifest.get(key)):
                    raise RuntimeError("existing raw artifact and manifest disagree for {}".format(key))
        manifest_hash = value.get("manifest_sha256")
        if isinstance(manifest_hash, str):
            expected_manifest_hash = sha256_bytes(
                (canonical_json(nested_manifest) + "\n").encode("utf-8")
            )
            if manifest_hash != expected_manifest_hash:
                raise RuntimeError("existing raw artifact manifest hash mismatch")
    if manifest_payload is not None and raw_payload is None:
        status = str(manifest_payload.get("artifact_status", "")).lower()
        if status in {"completed", "stopped"}:
            raise RuntimeError("final stage manifest has no matching raw artifact")
    if raw_payload is not None and manifest_payload is None:
        status = str(raw_payload.get("artifact_status", "")).lower()
        if status in {"completed", "stopped"}:
            raise RuntimeError("final raw artifact has no matching stage manifest")

    _preflight_existing_checkpoints(
        output_dir,
        expected_identity=expected_identity,
        expected_case_ids=expected_case_ids,
    )

    status_values = {
        str(payload.get("artifact_status", "")).lower()
        for payload in (manifest_payload, raw_payload)
        if payload is not None
    }
    if status_values & {"completed", "stopped"}:
        final_status = "completed" if "completed" in status_values else "stopped"
        if status_values != {final_status}:
            raise RuntimeError("existing final artifacts disagree on {} status".format(final_status))
        if manifest_payload is None or raw_payload is None:
            raise RuntimeError("{} output is missing a final artifact".format(final_status))
        table_manifest = manifest_payload.get("table_manifest")
        if not isinstance(table_manifest, Mapping):
            raise RuntimeError("{} output lacks table manifest".format(final_status))
        for specification in table_manifest.values():
            if (
                not isinstance(specification, Mapping)
                or specification.get("schema_version") != SCHEMA_VERSION
                or not isinstance(specification.get("path"), str)
            ):
                raise RuntimeError("{} output has invalid table declaration".format(final_status))
            table_path = output_dir / specification["path"]
            if not table_path.is_file():
                raise RuntimeError("{} output is missing table {}".format(final_status, specification["path"]))
            declared_hash = specification.get("sha256")
            if not isinstance(declared_hash, str):
                raise RuntimeError("{} output table lacks sha256: {}".format(final_status, specification["path"]))
            if sha256_bytes(table_path.read_bytes()) != declared_hash:
                raise RuntimeError("{} output table hash mismatch: {}".format(final_status, specification["path"]))
            expected_row_count = specification.get("row_count")
            if isinstance(expected_row_count, bool) or not isinstance(expected_row_count, int) or expected_row_count < 0:
                raise RuntimeError("{} output table has invalid row count: {}".format(final_status, specification["path"]))
            try:
                table_rows = table_path.read_bytes().splitlines()
            except OSError as exc:
                raise RuntimeError("cannot read {} output table {}".format(final_status, specification["path"])) from exc
            if expected_row_count != len(table_rows):
                raise RuntimeError("{} output table row count mismatch: {}".format(final_status, specification["path"]))
            for table_row in table_rows:
                try:
                    parsed_row = json.loads(table_row.decode("utf-8"))
                except (UnicodeDecodeError, json.JSONDecodeError) as exc:
                    raise RuntimeError("{} output table has invalid JSON: {}".format(final_status, specification["path"])) from exc
                if not isinstance(parsed_row, Mapping):
                    raise RuntimeError("{} output table row is not an object: {}".format(final_status, specification["path"]))
        if not (output_dir / "summary.json").is_file():
            raise RuntimeError("{} output is missing summary.json".format(final_status))
        declared_summary_hash = manifest_payload.get("summary_sha256")
        if not isinstance(declared_summary_hash, str):
            raise RuntimeError("{} output lacks summary sha256".format(final_status))
        raw_summary_hash = raw_payload.get("summary_sha256")
        if raw_summary_hash != declared_summary_hash:
            raise RuntimeError("{} output raw summary hash mismatch".format(final_status))
        summary_path = output_dir / "summary.json"
        if sha256_bytes(summary_path.read_bytes()) != declared_summary_hash:
            raise RuntimeError("{} output summary hash mismatch".format(final_status))
        return final_status
    if "stopped" in status_values and status_values - {"stopped", "partial", ""}:
        raise RuntimeError("existing final artifacts disagree on stopped status")
    return "resume" if (manifest_payload is not None or raw_payload is not None or (output_dir / "checkpoints").exists()) else "new"


def _validated_structural_gates(
    stage: str,
    *,
    implementation_review: Any = None,
    smoke_decision: Any = None,
    pre_screen_review: Any = None,
    promotion_decision: Any = None,
    prior_regression_decision: Any = None,
) -> Dict[str, Any]:
    """Expose only gates carried by identity-validated prerequisite artifacts.

    This helper is called after the corresponding manifest validator has
    accepted each decision.  A missing claim remains ``inconclusive``; it is
    never promoted to a passing boolean merely because a decision had a
    passing status.
    """

    sources: Dict[str, Any] = {}
    for name, artifact in (
        ("implementation_review", implementation_review),
        ("smoke_decision", smoke_decision),
        ("pre_screen_review", pre_screen_review),
        ("promotion_decision", promotion_decision),
        ("prior_regression_decision", prior_regression_decision),
    ):
        if artifact is not None:
            payload = _decision_payload(artifact)
            sources[name] = {
                "sha256": _decision_hash(artifact),
                "status": str(payload.get("status", payload.get("decision", ""))).lower(),
                "protocol_sha256": payload.get("protocol_sha256", payload.get("protocol_hash")),
                "code_identity_sha256": payload.get(
                    "code_identity_sha256", payload.get("code_identity_hash")
                ),
            }

    result: Dict[str, Any] = {
        "source_decisions": sources,
        "exact_parity": "inconclusive",
        "leakage_no_refit": "inconclusive",
        "determinism": "inconclusive",
    }
    aliases = {
        "exact_parity": ("exact_parity", "parity"),
        "leakage_no_refit": ("leakage_no_refit", "leakage", "no_refit"),
        "determinism": ("determinism", "deterministic"),
    }
    for gate, names in aliases.items():
        observed: Any = None
        for artifact in (
            implementation_review,
            smoke_decision,
            pre_screen_review,
            promotion_decision,
            prior_regression_decision,
        ):
            if artifact is None:
                continue
            payload = _decision_payload(artifact)
            nested = payload.get("structural_gates", payload.get("gates", {}))
            for name in names:
                if name in payload:
                    observed = payload[name]
                elif isinstance(nested, Mapping) and name in nested:
                    observed = nested[name]
                if observed is not None:
                    break
            if observed is not None:
                break
        if isinstance(observed, Mapping):
            observed = observed.get("status", observed.get("passed"))
        if observed is True or str(observed).lower() in {"pass", "passed", "go", "true"}:
            result[gate] = "pass"
        elif observed is False or str(observed).lower() in {"fail", "failed", "false"}:
            result[gate] = "fail"
    return _json_safe(result)


def _stage_manifest(
    stage: str,
    cases: Sequence[Any],
    methods: Sequence[str],
    schedule: Sequence[Mapping[str, Any]],
    provenance: Mapping[str, Any],
    *,
    authorization_hashes: Mapping[str, Optional[str]],
    environment: Optional[Mapping[str, Any]] = None,
) -> Dict[str, Any]:
    return {
        "schema_version": SCHEMA_VERSION,
        "stage": stage,
        "protocol_sha256": manifest.verify_protocol_hash(),
        "case_count": len(cases),
        "method_ids": list(methods),
        "method_row_count": len(cases) * len(methods),
        "case_grid_sha256": manifest.case_grid_sha256(cases),
        "schedule_seed": SCHEDULE_SEED,
        "planned_order": [_json_safe(row) for row in schedule],
        "provenance": _json_safe(provenance),
        "environment": _json_safe(environment or _environment()),
        "authorization_hashes": _json_safe(dict(authorization_hashes)),
        "warmup_excluded": True,
        "output_root_excluded_from_code_identity": True,
        "artifact_status": "partial",
        "expected_case_count": len(cases),
        "observed_case_count": 0,
        "expected_method_row_count": len(cases) * len(methods),
        "observed_method_row_count": 0,
    }


def _summaries(
    rows: Sequence[Mapping[str, Any]],
    *,
    outcomes_redacted: bool,
    determinism: Optional[Mapping[str, Any]] = None,
    structural_gates: Optional[Mapping[str, Any]] = None,
) -> Dict[str, Any]:
    grouped: Dict[str, List[Mapping[str, Any]]] = {}
    for row in rows:
        grouped.setdefault(str(row.get("candidate_id")), []).append(row)
    result: Dict[str, Any] = {
        "schema_version": SCHEMA_VERSION,
        "outcomes_redacted": bool(outcomes_redacted),
        "candidates": {},
    }
    if determinism is not None:
        result["determinism"] = _json_safe(determinism)
    if structural_gates is not None:
        result["structural_gates"] = _json_safe(structural_gates)
    if outcomes_redacted:
        result["candidate_count"] = len(grouped)
        result["ranking_available"] = False
        return result
    for candidate, group in sorted(grouped.items()):
        scores = [float(row["candidate_score"]) for row in group if row.get("candidate_score") is not None and row.get("status") == "ok"]
        result["candidates"][candidate] = {
            "row_count": len(group),
            "ok_count": sum(row.get("status") == "ok" for row in group),
            "error_count": sum(row.get("status") == "error" for row in group),
            "candidate_score_mean": float(np.mean(scores)) if scores else None,
        }
    return result


def run_stage(
    stage: str,
    output: Union[str, Path],
    *,
    implementation_review: Any = None,
    smoke_decision: Any = None,
    pre_screen_review: Any = None,
    promotion_decision: Any = None,
    prior_regression_decision: Any = None,
    cases: Optional[Sequence[Any]] = None,
    limit: Optional[int] = None,
    warmup: bool = True,
    resume: bool = True,
    run_resources: bool = True,
) -> Dict[str, Path]:
    """Run one authorized stage with atomic checkpoints.

    ``limit`` is accepted only for smoke.  Development and confirmation are
    frozen stage grids and cannot be silently truncated.  Historical prior
    regression is owned by ``prior_regression.py`` and is not a generic stage.
    """

    stage_value = validate_stage(stage)
    subset_requested = limit is not None
    provenance = _provenance()
    authorization = _authorize_stage(
        stage_value,
        provenance=provenance,
        implementation_review=implementation_review,
        smoke_decision=smoke_decision,
        pre_screen_review=pre_screen_review,
        promotion_decision=promotion_decision,
        prior_regression_decision=prior_regression_decision,
    )
    locked = authorization if isinstance(authorization, str) else None
    if stage_value == "confirmation":
        # The opaque confirmation token intentionally carries hashes only;
        # recover the already-validated lock from the supplied promotion
        # decision for the fixed method/resource sets.
        locked = manifest.validate_promotion_decision(
            promotion_decision,
            protocol_hash=manifest.verify_protocol_hash(),
            code_identity_hash=provenance.get("code_identity_sha256"),
        )
    if cases is None:
        cases = stage_cases(stage_value)
        cases_supplied = False
    else:
        cases_supplied = True
    cases_tuple = tuple(cases)
    if limit is not None:
        if stage_value != "smoke":
            raise ValueError("only smoke accepts --limit")
        if isinstance(limit, bool) or int(limit) <= 0:
            raise ValueError("limit must be a positive integer")
        cases_tuple = cases_tuple[: int(limit)]
    if not cases_tuple:
        raise ValueError("stage case grid cannot be empty")
    if stage_value != "smoke" or limit is None:
        _validate_stage_cases(stage_value, cases_tuple, cases_supplied)
    if stage_value == "confirmation" and authorization is None:
        raise PermissionError("confirmation requires validated authorization")
    if stage_value in {"smoke", "development"}:
        methods = METHOD_IDS
    elif stage_value == "confirmation":
        methods = manifest.methods_for_stage(stage_value, locked)
    schedule = list(manifest.planned_execution_order(cases_tuple, methods, schedule_seed=SCHEDULE_SEED))
    manifest.validate_execution_order(schedule, [case_id(case) for case in cases_tuple], methods, schedule_seed=SCHEDULE_SEED)
    output_dir = Path(output)
    environment = _environment()
    stage_meta = _stage_manifest(
        stage_value,
        cases_tuple,
        methods,
        schedule,
        provenance,
        authorization_hashes={
            "implementation_review_sha256": _decision_hash(implementation_review) if implementation_review is not None else None,
            "smoke_decision_sha256": _decision_hash(smoke_decision) if smoke_decision is not None else None,
            "smoke_manifest_sha256": (
                _decision_payload(smoke_decision).get("input_manifest_sha256")
                if smoke_decision is not None
                else None
            ),
            "pre_screen_smoke_decision_sha256": (
                _decision_payload(pre_screen_review).get(
                    "smoke_decision_sha256",
                    _decision_payload(pre_screen_review).get("smoke_decision_hash"),
                )
                if pre_screen_review is not None
                else None
            ),
            "pre_screen_review_sha256": _decision_hash(pre_screen_review) if pre_screen_review is not None else None,
            "promotion_decision_sha256": _decision_hash(promotion_decision) if promotion_decision is not None else None,
            "prior_regression_decision_sha256": _decision_hash(prior_regression_decision) if prior_regression_decision is not None else None,
        },
        environment=environment,
    )
    if locked is not None:
        stage_meta["locked_candidate"] = str(locked)
    if promotion_decision is not None:
        stage_meta["promotion_decision_sha256"] = _decision_hash(promotion_decision)
    structural_gates = _validated_structural_gates(
        stage_value,
        implementation_review=implementation_review,
        smoke_decision=smoke_decision,
        pre_screen_review=pre_screen_review,
        promotion_decision=promotion_decision,
        prior_regression_decision=prior_regression_decision,
    )
    stage_meta["structural_gates"] = structural_gates
    # Existing output identity is checked before creating the directory or
    # writing the initial partial manifest.  This prevents an invocation for a
    # different protocol/code/stage/lock/source set from appending checkpoints
    # or overwriting a finalized artifact before the mismatch is noticed.
    output_state = _preflight_existing_output(
        output_dir,
        stage_meta=stage_meta,
        provenance=provenance,
        expected_case_ids=[case_id(case) for case in cases_tuple],
    )
    if output_state in {"completed", "stopped"}:
        return {
            "manifest": output_dir / "manifest.json",
            "raw": output_dir / "raw_results.json",
            "summary": output_dir / "summary.json",
            "tables": output_dir / "tables",
        }
    output_dir.mkdir(parents=True, exist_ok=True)
    _atomic_write_bytes(output_dir / "manifest.json", (canonical_json(stage_meta) + "\n").encode("utf-8"))

    warmup_payload: Optional[Dict[str, Any]] = None
    measured_cases = cases_tuple
    determinism: Dict[str, Any] = {
        "status": "inconclusive",
        "warmup_excluded": True,
        "basis": "no warmup requested",
        "candidates": {},
    }
    if warmup and cases_tuple:
        warmup_payload = _run_case(
            cases_tuple[0],
            authorization=authorization,
            methods=methods,
            schedule=schedule,
            expose_outcomes=stage_value != "smoke",
            include_reference_outcomes=stage_value != "smoke",
        )
        determinism["basis"] = "excluded first-case warmup versus first measured case"
        measured_cases = cases_tuple
    checkpoints: List[Dict[str, Any]] = []
    case_bank_hashes: Dict[str, Dict[str, str]] = {}
    stopped: Optional[Dict[str, Any]] = None
    for position, case in enumerate(measured_cases):
        bank_hashes = _generator_bank_hashes(case, authorization)
        case_bank_hashes[case_id(case)] = bank_hashes
        identity = {
            **_case_identity(case),
            "stage": stage_value,
            "methods": list(methods),
            "schedule_seed": SCHEDULE_SEED,
            "code_identity_sha256": provenance.get("code_identity_sha256"),
            "protocol_sha256": stage_meta.get("protocol_sha256"),
            "environment_sha256": digest(environment),
            "source_hashes": provenance.get("source_hashes"),
            "generator_bank_hashes": bank_hashes,
            "generator_bank_hashes_sha256": digest(bank_hashes),
            "candidate_definitions_sha256": _candidate_definitions_hash(methods),
            "planned_schedule_sha256": digest(schedule),
            "authorization_hashes": stage_meta.get("authorization_hashes"),
        }
        # The first measured case is always rerun when an excluded warmup is
        # requested.  Reusing an old checkpoint here would make the required
        # structural repeat unverifiable after resume.
        existing = (
            _read_checkpoint(output_dir, case_id(case), identity)
            if resume and not (warmup_payload is not None and position == 0)
            else None
        )
        if existing is not None:
            checkpoint = existing
        else:
            try:
                measured_payload = _run_case(
                    case,
                    authorization=authorization,
                    methods=methods,
                    schedule=schedule,
                    expose_outcomes=stage_value != "smoke",
                    include_reference_outcomes=stage_value != "smoke",
                )
            except Exception as exc:
                checkpoint = {
                    "case": _case_identity(case),
                    "case_id": case_id(case),
                    "rows": [],
                    "status": "error",
                    "error": "{}: {}".format(type(exc).__name__, exc),
                    "stop_reason": _stop_reason(exc),
                }
                _write_checkpoint(output_dir, checkpoint, identity)
                checkpoints.append(checkpoint)
                stopped = {
                    "status": "stopped",
                    "scope": "whole_stage",
                    "case_id": case_id(case),
                    "reason": _stop_reason(exc),
                    "completed_case_count": len(checkpoints),
                }
                break
            if warmup_payload is not None and position == 0:
                try:
                    verify_deterministic_rows(warmup_payload["rows"], measured_payload["rows"])
                    if stage_value == "smoke" and warmup_payload.get("_smoke_score_digest") != measured_payload.get("_smoke_score_digest"):
                        raise AssertionError("candidate scores differ across deterministic smoke repeats")
                    determinism = {
                        **determinism,
                        "status": "pass",
                        "exact": True,
                        "candidate_signatures": {
                            str(row.get("candidate_id")): digest(_determinism_signature(row))
                            for row in measured_payload.get("rows", ())
                        },
                    }
                except AssertionError as exc:
                    determinism = {**determinism, "status": "fail", "exact": False, "error": str(exc)}
                    stopped = {
                        "status": "stopped",
                        "scope": "whole_stage",
                        "case_id": case_id(case),
                        "reason": "nondeterminism",
                        "completed_case_count": position + 1,
                    }
            # Private repeat evidence is consumed above and must never enter a
            # checkpoint, normalized table, summary, or raw artifact.
            measured_payload.pop("_smoke_score_digest", None)
            checkpoint = measured_payload
            if stage_value == "smoke":
                checkpoint = {
                    **measured_payload,
                    # _run_case already redacts after its in-memory repeat
                    # digest is captured.  Do not redact a second time: that
                    # would erase pair identities and state-hash evidence.
                    "rows": list(measured_payload.get("rows", ())),
                    "outcomes_redacted": True,
                }
            _write_checkpoint(output_dir, checkpoint, identity)
        checkpoints.append(checkpoint)
        statuses = [str(row.get("status")) for row in checkpoint.get("rows", ()) if row.get("candidate_id") in methods]
        if any(status != "ok" for status in statuses):
            # A fit/score/diagnostic exception is an incomplete paired block,
            # not evidence for excluding one candidate.  Stop the whole stage
            # so statistics cannot silently compare a surviving subset.
            failed_rows = [
                row for row in checkpoint.get("rows", ())
                if row.get("candidate_id") in methods and row.get("status") != "ok"
            ]
            stopped = {
                "status": "stopped",
                "scope": "whole_stage",
                "case_id": case_id(case),
                "reason": str((failed_rows[0] if failed_rows else {}).get("stop_reason") or "candidate_error"),
                "error": (failed_rows[0] if failed_rows else {}).get("error"),
                "completed_case_count": len(checkpoints),
            }
            break
        if stopped is not None:
            break
    all_rows = _flatten_rows(checkpoints)
    resource_rows: List[Dict[str, Any]] = []
    resource_failure: Optional[Dict[str, Any]] = None
    if run_resources and stage_value in {"development", "confirmation"} and stopped is None:
        from . import resource_benchmark

        resource_candidates = (
            ("B", "L") + PROMOTABLE_CANDIDATES
            if stage_value == "development"
            else ("B", str(locked))
        )
        try:
            resource_rows = resource_benchmark.run_resource_benchmark(
                cases_tuple,
                resource_candidates,
                code_identity_sha256=str(provenance.get("code_identity_sha256")),
                protocol_sha256=str(stage_meta.get("protocol_sha256")),
                stage=stage_value,
                locked_candidate=locked,
                authorization=authorization,
            )
        except Exception as exc:
            # Missing/erroring fresh-process evidence is not a candidate
            # exclusion.  Preserve the completed case checkpoints but stop
            # the stage as resource evidence is mandatory for production.
            resource_failure = {
                "status": "error",
                "scope": "whole_stage",
                "reason": "runtime_or_resource",
                "error": "{}: {}".format(type(exc).__name__, exc),
            }
            stopped = resource_failure
    elif not run_resources and stage_value in {"development", "confirmation"}:
        # Keep an explicit debug seam for focused tests, but never label a
        # production outcome complete without the mandatory R0-R3 rows.
        resource_failure = {
            "status": "inconclusive",
            "scope": "whole_stage",
            "reason": "resource_measurement_not_requested",
        }
    observed_case_count = len(checkpoints)
    observed_method_row_count = sum(
        sum(1 for row in checkpoint.get("rows", ()) if row.get("candidate_id") in methods)
        for checkpoint in checkpoints
    )
    if stopped is not None:
        artifact_status = "stopped"
    elif resource_failure is not None:
        artifact_status = "partial"
    elif subset_requested:
        # A smoke limit is a focused debug seam; it can exercise plumbing but
        # cannot satisfy the frozen 30-case artifact contract.
        artifact_status = "partial"
    elif (
        stage_value in {"smoke", "development", "confirmation"}
        and determinism.get("status") != "pass"
    ):
        # A frozen production artifact without the required structural repeat
        # is not eligible for analysis.  Keep its rows for debugging/resume,
        # but make the incomplete status explicit.
        artifact_status = "partial"
    elif observed_case_count == len(cases_tuple) and observed_method_row_count == len(cases_tuple) * len(methods):
        artifact_status = "completed"
    else:
        artifact_status = "partial"

    # Assemble normalized tables first.  The final manifest must declare the
    # exact table paths/hashes used by statistics.load_normalized_artifact;
    # writing it before this step leaves an apparently complete artifact with
    # no table declarations.
    table_manifest = assemble_tables(output_dir, checkpoints, resource_rows)
    structural_gates = {
        **structural_gates,
        "stage_determinism": str(determinism.get("status", "inconclusive")),
    }
    # Summary content depends only on measured rows and structural gates, not
    # on the manifest itself.  Build and hash it before finalizing the
    # manifest so a completed output can later be accepted read-only only
    # after its summary bytes have been verified.
    summary = _summaries(
        all_rows,
        outcomes_redacted=stage_value == "smoke",
        determinism=determinism,
        structural_gates=structural_gates,
    )
    summary_bytes = (canonical_json(summary) + "\n").encode("utf-8")
    summary_sha256 = sha256_bytes(summary_bytes)
    stage_meta = {
        **stage_meta,
        "artifact_status": artifact_status,
        "observed_case_count": observed_case_count,
        "observed_method_row_count": observed_method_row_count,
        "determinism": _json_safe(determinism),
        "structural_gates": _json_safe(structural_gates),
        "table_manifest": _json_safe(table_manifest),
        "resource_row_count": len(resource_rows),
        "resource_failure": _json_safe(resource_failure),
        "summary_sha256": summary_sha256,
    }
    manifest_bytes = (canonical_json(stage_meta) + "\n").encode("utf-8")
    _atomic_write_bytes(output_dir / "manifest.json", manifest_bytes)
    final_manifest_sha256 = sha256_bytes(manifest_bytes)
    bank_hashes: Dict[str, Any] = {
        str(case_identifier): hashes
        for case_identifier, hashes in case_bank_hashes.items()
    }
    for checkpoint in checkpoints:
        for row in checkpoint.get("rows", ()):
            metadata = row.get("fixture_metadata", {}) or {}
            if metadata.get("bank_hashes") is not None:
                bank_hashes[str(checkpoint.get("case_id"))] = metadata.get("bank_hashes")
    raw_payload = {
        "schema_version": SCHEMA_VERSION,
        "stage": stage_value,
        "manifest": stage_meta,
        "manifest_sha256": final_manifest_sha256,
        "table_manifest": table_manifest,
        "summary_sha256": summary_sha256,
        "provenance": _json_safe(provenance),
        "generator_bank_hashes": _json_safe(bank_hashes),
        "environment": environment,
        "artifact_status": artifact_status,
        "expected_case_count": len(cases_tuple),
        "observed_case_count": observed_case_count,
        "expected_method_row_count": len(cases_tuple) * len(methods),
        "observed_method_row_count": observed_method_row_count,
        "determinism": _json_safe(determinism),
        "warmup": {
            "enabled": bool(warmup),
            "excluded_from_tables": True,
            "excluded_from_summaries": True,
            "case_id": case_id(cases_tuple[0]) if warmup and cases_tuple else None,
            "structural_signature": (
                digest(
                    [
                        _determinism_signature(row)
                        for row in warmup_payload.get("rows", ())
                    ]
                )
                if warmup_payload is not None
                else None
            ),
        },
        "checkpoint_count": len(checkpoints),
        "stopped": stopped,
        "resource_row_count": len(resource_rows),
    }
    _atomic_write_bytes(output_dir / "raw_results.json", (canonical_json(raw_payload) + "\n").encode("utf-8"))
    _atomic_write_bytes(output_dir / "summary.json", summary_bytes)
    if stopped is not None:
        _atomic_write_bytes(output_dir / "stopped.json", (canonical_json(stopped) + "\n").encode("utf-8"))
    return {
        "manifest": output_dir / "manifest.json",
        "raw": output_dir / "raw_results.json",
        "summary": output_dir / "summary.json",
        "tables": output_dir / "tables",
    }


def _environment() -> Dict[str, Any]:
    packages: Dict[str, str] = {}
    for package in ("numpy", "scipy", "scikit-learn", "joblib"):
        try:
            packages[package] = importlib.metadata.version(package)
        except importlib.metadata.PackageNotFoundError:
            packages[package] = "unavailable"
    return {
        "python_version": platform.python_version(),
        "python_implementation": platform.python_implementation(),
        "platform": platform.platform(),
        "machine": platform.machine(),
        "python_executable": sys.executable,
        "package_versions": packages,
        "thread_environment": dict(THREAD_ENVIRONMENT),
    }


def _cli() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("stage", choices=STAGES)
    parser.add_argument("--output", required=True)
    parser.add_argument("--limit", type=int)
    parser.add_argument("--no-warmup", action="store_true")
    parser.add_argument("--implementation-review", type=Path)
    parser.add_argument("--smoke-decision", type=Path)
    parser.add_argument("--pre-screen-review", type=Path)
    parser.add_argument("--promotion-decision", type=Path)
    parser.add_argument("--prior-regression-decision", type=Path)
    parser.add_argument(
        "--no-resources",
        action="store_true",
        help="debug/test seam: omit mandatory fresh-process resource measurements",
    )
    parser.add_argument("--no-resume", action="store_true")
    args = parser.parse_args()
    run_stage(
        args.stage,
        args.output,
        limit=args.limit,
        warmup=not args.no_warmup,
        resume=not args.no_resume,
        run_resources=not args.no_resources,
        implementation_review=args.implementation_review,
        smoke_decision=args.smoke_decision,
        pre_screen_review=args.pre_screen_review,
        promotion_decision=args.promotion_decision,
        prior_regression_decision=args.prior_regression_decision,
    )
    return 0


