def stage_cases(stage: str) -> Tuple[Any, ...]:
    """Return planned identities; this does not allocate confirmation banks."""

    stage_value = validate_stage(stage)
    if stage_value == "smoke":
        return tuple(fixtures.smoke_cases())
    if stage_value == "development":
        return tuple(fixtures.development_cases())
    if stage_value == "confirmation":
        return tuple(fixtures.confirmation_cases())
    raise AssertionError("validate_stage accepted an unsupported stage")


def build_stage_cases(stage: str) -> Tuple[Any, ...]:
    return stage_cases(stage)


def _case_identity(case: Any) -> Dict[str, Any]:
    identity = getattr(case, "identity", None)
    if callable(identity):
        return _json_safe(identity())
    if isinstance(case, Mapping):
        return _json_safe(dict(case))
    raise TypeError("case must expose identity() or be a mapping")


def case_id(case: Any) -> str:
    value = getattr(case, "case_id", None)
    if value is not None:
        return str(value)
    identity = _case_identity(case)
    if "case_id" not in identity:
        raise ValueError("case identity lacks case_id")
    return str(identity["case_id"])


def _case_dataset(case: Any, authorization: Any = None) -> Any:
    stage = str(getattr(case, "stage", "")).lower()
    if stage == "confirmation":
        if authorization is None:
            raise PermissionError(
                "confirmation data require validated authorization immediately before generation"
            )
        # This is the sole confirmation-generation call in the runner.
        return fixtures.generate_confirmation_dataset(case, authorization=authorization)
    if stage in {"smoke", "development"}:
        generator = getattr(fixtures, "generate_dataset", None)
        if generator is None:
            generator = fixtures.generate_development_dataset
        return generator(case)
    raise PermissionError("prior regression data require an explicit dataset factory")


def _generator_bank_hashes(case: Any, authorization: Any = None) -> Dict[str, str]:
    """Return the frozen latent-bank hashes used by a case identity.

    Computing these hashes before checkpoint lookup makes resume sensitive to
    generator/bank changes, not merely to the candidate source file.  The
    confirmation branch is reached only after ``_authorize_stage`` has
    validated its opaque token.
    """

    stage = str(getattr(case, "stage", "")).lower()
    if stage not in {"smoke", "development", "confirmation"}:
        raise PermissionError("generator bank hashes require an authorized fixture stage")
    banks = fixtures.latent_banks(
        int(getattr(case, "seed")),
        stage=stage,
        authorization=authorization,
    )
    return dict(fixtures.bank_hashes(banks))


